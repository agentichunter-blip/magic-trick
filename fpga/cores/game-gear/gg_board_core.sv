// Game Gear core logic driven by the existing 67.108864 MHz xclk. No physical IO.
module gg_board_core(
 input [128:0] gg_code,
 input gg_clear,
 input clk, reset_n, rom_ready, quiesce,
 input [6:0] buttons,
 input [7:0] rom_do,
 output [23:0] rom_a,
