 output [15:0] audioL,audioR,
 output ce_pix, hblank, vblank,
 output ram_we, output [13:0] ram_a, output [7:0] ram_d
);
wire ce_cpu,ce_vdp,ce_sp;
gg_clock_enables clock_enables(.clk(clk),.reset_n(reset_n),.cpu(ce_cpu),
 .vdp(ce_vdp),.pixel(ce_pix),.sprite(ce_sp));
wire [7:0] vcounter_cpu;
wire mask_column,smode_M1,smode_M2,smode_M3,smode_M4;
wire [14:0] nvram_a;
wire [7:0] nvram_d;
wire nvram_we;
reg [7:0] ram_q,nvram_q;
reg [7:0] ram[0:16383];
// 16 KiB cartridge RAM (was 32 KiB) frees 8 BSRAM for the ROM cache. GG
// cartridges use at most 8-16 KiB; bank bit 14 aliases.
reg [7:0] nvram[0:16383];
always @(posedge clk) begin
 ram_q <= ram_we ? ram_d : ram[ram_a];
 nvram_q <= nvram_we ? nvram_d : nvram[nvram_a[13:0]];
 if(ram_we) ram[ram_a] <= ram_d;
 if(nvram_we) nvram[nvram_a[13:0]] <= nvram_d;
end
