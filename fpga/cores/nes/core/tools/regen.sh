#!/bin/bash
# Regenerate rtl/gen/ from the pristine NES_MiSTer clone.
set -euo pipefail
W="$(cd "$(dirname "$0")/.." && pwd)"
G=${GHDL:-$(cd "$W/.." && pwd)/toolchains/oss-cad-suite/bin/ghdl}
python3 -I "$W/syn/tools/prep.py" "$W" > /dev/null
python3 -I "$W/tools/gen_rtl.py" "$W"
T=$(mktemp -d)
cd "$T"   # ghdl -m drops objects/executables in the cwd
F="--std=08 -frelaxed -fsynopsys --workdir=$T"
R="$W/NES_MiSTer/rtl"
$G -i $F "$R/bus_savestates.vhd" "$R/t65/T65_Pack.vhd" "$R/t65/T65_ALU.vhd" "$R/t65/T65_MCode.vhd" "$W/rtl/gen/T65.vhd" "$W/rtl/t65_nes.vhd"
$G -m $F t65_nes
{ echo "// GENERATED by tools/regen.sh: GHDL --synth of rtl/t65_nes.vhd (NES_MiSTer T65). Do not edit."
  $G --synth $F --out=verilog t65_nes | perl -pe 's/\b(break|continue|return|do|int|bit|logic)\b/$1_n65/g'; } > "$W/rtl/gen/t65_nes_netlist.v"
rm -rf "$T"
echo "rtl/gen/t65_nes_netlist.v: $(wc -l < "$W/rtl/gen/t65_nes_netlist.v") lines"
