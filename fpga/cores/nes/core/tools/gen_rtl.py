"""Generate rtl/gen/ (the patched MiSTer NES core used by the Chromatic build and by sim/).

Run from anywhere:
    python3 -I nes-work/syn/tools/prep.py nes-work      # Gowin compatibility pass -> syn/src
    python3 -I nes-work/tools/gen_rtl.py nes-work       # this script -> rtl/gen
(tools/regen.sh does both, plus the GHDL netlist of T65.)

Input is syn/src (generated by the feasibility probe's prep.py from the pristine clone; see
FEASIBILITY.md section 1 for those fixes: regs_savestates imports, always @*, wire->logic,
~300 hoisted forward-referenced declarations, reduced cart_top, OAM-in-block-RAM rewrite).
This script adds:
  * ppu.sv   = ppu_oam.sv (OAM + secondary OAM rewrite) with the composite-video generator
               removed (composite_a/b tied to 0; the RGB path is unaffected).
  * nes.sv   = composite_board removed. Added outputs for the board's memory side:
               cpu_rom_hint (CPU cycle is a read of the cartridge, used to prefetch PRG lines),
               ppu_dot (= ppu_ce, for the pixel strobe).
  * cart.sv  = cart_full.sv (mappers 0,1,2,3,4,7,9,10,11,66,69,71,21-25) with the tri0/tri1
               mapper buses replaced by explicit OR/AND merges of per-mapper outputs.
  * mappers.sv = only the mapper modules cart.sv needs, with every `inout *_b` port turned into
               an output that drives 0 (or all ones for the *_dout_b data buses) when disabled.
  * apu.sv, regs_savestates.sv copied; cheatcodes.sv = CODES rewritten for the Chromatic (Game
               Genie, 16 codes, table written on gg_clk = free-running xclk; nes.sv gets a gg_clk input).
Not used from the clone: savestates.vhd/statemanager.vhd/bus_savestates.vhd (re-written in
SystemVerilog in rtl/nes_savestates.sv with the reduced region table), T65 goes through GHDL
(rtl/t65_nes.vhd wrapper -> rtl/gen/t65_nes_netlist.v, see tools/regen.sh).
"""
import re, sys
from pathlib import Path

work = Path(sys.argv[1]).resolve()
src = work / 'syn' / 'src'
out = work / 'rtl' / 'gen'
out.mkdir(parents=True, exist_ok=True)

def rd(n):
    return (src / n).read_text()

def sub1(text, old, new, regex=False, count=1):
    if regex:
        t2, n = re.subn(old, new, text, count=count, flags=re.S)
    else:
        n = text.count(old)
        t2 = text.replace(old, new) if count == 0 else text.replace(old, new, count)
    assert n >= 1, ('patch not applied', old[:100])
    return t2

HDR = '// GENERATED by tools/gen_rtl.py from NES_MiSTer (see REVISION) via syn/tools/prep.py. Do not edit.\n'

# ---------------------------------------------------------------- ppu.sv
# (ppu_stock.sv: the same without the OAM rewrite, for A/B tests in sim/ only - too large.)
for src_name, dst_name in [('ppu.sv', 'ppu_stock.sv'), ('ppu_oam.sv', 'ppu.sv')]:
  t = rd(src_name)
  # composite video generator (pin-21 voltage model) is not needed: drop the three instances.
  t = sub1(t, r'ppu_video_phase video_carrier\(.*?\);\s*', '', regex=True)
  t = sub1(t, r'ppu_video_color video_color\(.*?\);\s*', '', regex=True)
  t = sub1(t, r'ppu_video_dac video_dac\(.*?\);\s*',
           'assign composite_a = 24\'sd0;\nassign composite_b = 24\'sd0;\n', regex=True)
  for m in ['ppu_video_phase', 'ppu_video_color', 'ppu_video_dac']:
      t = sub1(t, r'\nmodule ' + m + r'\b.*?\nendmodule[^\n]*', '\n', regex=True)
  t = sub1(t, 'inout   [1:0] sys_type', 'input   [1:0] sys_type')
  if dst_name == 'ppu.sv':
      t = sub1(t, '\tif (oam_we) oam[oam_ra] <= oam_wd;\n\toam_q <= oam[oam_ra];',
               '\t// write-through (GW5A BSRAM has no read-before-write mode); oam_q settles within a dot\n'
               '\tif (oam_we) begin oam[oam_ra] <= oam_wd; oam_q <= oam_wd; end\n'
               '\telse oam_q <= oam[oam_ra];')
  (out / dst_name).write_text(HDR + t)

# ---------------------------------------------------------------- nes.sv
t = rd('nes.sv')
t = sub1(t, r'composite_board composite_board\(.*?\);',
         "assign composite_a = 24'sd0;\nassign composite_b = 24'sd0;", regex=True)
# Extra outputs for the board memory side.
t = sub1(t, '\tinput         SAVE_out_done   // should be one cycle high when write is done or read value is valid\n);',
         '\tinput         SAVE_out_done,  // should be one cycle high when write is done or read value is valid\n'
         '\toutput        cpu_rom_hint,   // Chromatic: CPU bus cycle reads the cartridge (PRG prefetch hint)\n'
         '\toutput        ppu_dot         // Chromatic: this master clock is a PPU dot (ppu_ce)\n);')
t = sub1(t, '\nendmodule\n\n\nmodule VsProtection',
         '\nassign cpu_rom_hint = mr_int && prg_allow && !ppu_cs && (addr[15:5] != 11\'b0100_0000_000);\n'
         'assign ppu_dot = ppu_ce;\n'
         'endmodule\n\n\nmodule VsProtection')
# Game Genie: the code table loads while the NES clock is stopped, so CODES gets the free-running clock.
t = sub1(t, '\tinput         gg_reset,\n', '\tinput         gg_reset,\n\tinput         gg_clk,         // Chromatic: free-running clock for the Game Genie code table\n')
t = sub1(t, 'CODES codes (\n\t.clk        (clk),\n', 'CODES codes (\n\t.clk        (clk),\n\t.cfg_clk    (gg_clk),\n')
(out / 'nes.sv').write_text(HDR + t)

# ---------------------------------------------------------------- cart.sv (explicit merges)
t = rd('cart_full.sv')
buses = {}   # name -> (width, kind)
for m in re.finditer(r'^(tri0|tri1)\s*(\[[^\]]+\])?\s*([^;]+);', t, flags=re.M):
    for n in m.group(3).split(','):
        buses[n.strip()] = (m.group(2) or '', m.group(1))
assert set(buses) >= {'prg_addr_b', 'prg_dout_b', 'irq_b'}, buses
t = re.sub(r'^(tri0|tri1)\b', 'wire', t, flags=re.M)
mapper_mods = ['MMC1', 'Mapper28', 'MMC2', 'MMC3', 'MMC4', 'Mapper66', 'Mapper69', 'Mapper71', 'VRC24']
conns = {b: [] for b in buses}
def fix_inst(m):
    mod, inst, body = m.group(1), m.group(2), m.group(3)
    for b in buses:
        body2 = re.sub(r'\(\s*' + b + r'\s*\)', f'({b}_{inst})', body)
        if body2 != body:
            conns[b].append(f'{b}_{inst}')
        body = body2
    return f'{mod} {inst}{body}'
t = re.sub(r'^(' + '|'.join(mapper_mods) + r')\s+(\w+)(\s*\(.*?\n\);)', fix_inst, t, flags=re.M | re.S)
decl = ['// ---- explicit merges of the mapper buses (were tri0/tri1; gen_rtl.py) ----']
for b, (w, kind) in buses.items():
    if conns[b]:
        decl.append(f'wire {w} {", ".join(conns[b])};')
        op = ' | ' if kind == 'tri0' else ' & '
        decl.append(f'assign {b} = {op.join(conns[b])};')
    else:
        decl.append(f"assign {b} = {'{$bits(' + b + '){1\'b0}}' if kind == 'tri0' else '{$bits(' + b + '){1\'b1}}'};")
# insert right after the hoisted declaration block's bus declarations
t = sub1(t, 'wire [13:0] chr_ain = chr_ex ? chr_ain_ex : chr_ain_orig;',
         '\n'.join(decl) + '\n\nwire [13:0] chr_ain = chr_ex ? chr_ain_ex : chr_ain_orig;')
(out / 'cart.sv').write_text(HDR + t)

# ---------------------------------------------------------------- mappers.sv
mods = {}
for f in ['MMC1.sv', 'MMC2.sv', 'MMC3.sv', 'generic.sv', 'Sunsoft.sv', 'VRC.sv']:
    for m in re.finditer(r'^module\s+(\w+).*?^endmodule[^\n]*', rd(f), flags=re.M | re.S):
        mods[m.group(1)] = m.group(0)
need, todo = [], list(mapper_mods)
while todo:
    n = todo.pop(0)
    if n in need:
        continue
    need.append(n)
    for k in mods:
        if k != n and re.search(r'^\s*' + k + r'\s+(#\s*\(.*?\)\s*)?\w+\s*\(', mods[n], flags=re.M):
            todo.append(k)
text = []
for n in need:
    body = mods[n]
    body = re.sub(r'^(\s*)inout(\s+(?:wire\s+)?(?:\[[^\]]+\]\s*)?\w+_b\b)', r'\1output\2', body, flags=re.M)
    def dz(m):
        name = m.group(1)
        fill = "'1" if name.endswith('dout_b') else "'0"
        return f'assign {name}{m.group(2)}: {fill};'
    body = re.sub(r"assign\s+(\w+_b)(\s*=.*?)\s*:\s*\d+'[hb][zZ]\s*;", dz, body)
    assert not re.search(r"'[hb][zZ]\b", body), (n, 'tristate left')
    assert 'inout' not in body, (n, 'inout left')
    text.append(body)
(out / 'mappers.sv').write_text('import regs_savestates::*;\n' + HDR + '\n\n'.join(text) + '\n')
print('mappers.sv modules:', ', '.join(need))

(out / 'cheatcodes.sv').write_text(HDR + '''// Game Genie for the Chromatic: Kitrinx's CODES (NES_MiSTer rtl/cheatcodes.sv) code layout
// {load pulse, flags (bit 96 = compare), address, compare, replace}, 16 codes. The table is written
// on cfg_clk (free-running xclk): codes are loaded while the NES clock (clk) is stopped. reset
// (gg_clear from the loader) is also on cfg_clk. Matching is combinational on the CPU bus, as upstream.
module CODES #(parameter MAX_CODES = 16) (
	input clk, input cfg_clk, input reset, input enable,
	input [15:0] addr_in, input [7:0] data_in, input [128:0] code,
	output available, output reg genie_ovr, output reg [7:0] genie_data);
	reg [MAX_CODES-1:0] valid = 0, cmp_f = 0;
	reg [MAX_CODES*16-1:0] addrs = 0;
	reg [MAX_CODES*8-1:0] cmps = 0, datas = 0;
	reg [4:0] index = 0;
	reg code_change = 0;
	assign available = |valid;
	always @(posedge cfg_clk) begin
		code_change <= code[128];
		if (reset) begin
			index <= 0;
			valid <= 0;
		end else if (code[128] && !code_change && index < MAX_CODES) begin
			valid[index] <= 1'b1;
			cmp_f[index] <= code[96];
			addrs[index*16 +: 16] <= code[79:64];
			cmps[index*8 +: 8] <= code[39:32];
			datas[index*8 +: 8] <= code[7:0];
			index <= index + 1'b1;
		end
	end
	integer i;
	always @* begin
		genie_ovr = 1'b0;
		genie_data = 8'h00;
		if (enable)
			for (i = 0; i < MAX_CODES; i = i + 1)
				if (valid[i] && addrs[i*16 +: 16] == addr_in && (!cmp_f[i] || cmps[i*8 +: 8] == data_in)) begin
					genie_ovr = 1'b1;
					genie_data = datas[i*8 +: 8];
				end
	end
endmodule
''')
for f in ['apu.sv', 'regs_savestates.sv']:
    (out / f).write_text(HDR + rd(f) if f != 'regs_savestates.sv' else rd(f))
print('wrote', ', '.join(sorted(p.name for p in out.glob('*.sv'))))

# ---------------------------------------------------------------- nes_palette_rom.sv
# MiSTer's default palette (video.sv pal_kitrinx_lut, "Kitrinx 2C02") with video.sv's
# emphasis attenuation, as a 512-entry ROM: address = {emphasis[2:0], colour[5:0]},
# data = 15-bit BGR555 {B[4:0], G[4:0], R[4:0]} (R in the low bits, like the Chromatic panel).
vt = (work / 'NES_MiSTer' / 'rtl' / 'video.sv').read_text()
m = re.search(r'pal_kitrinx_lut\[64\]\s*=\s*\'\{(.*?)\};', vt, flags=re.S)
pal = [int(x, 16) for x in re.findall(r"'h([0-9A-Fa-f]{6})", m.group(1))]
assert len(pal) == 64, len(pal)
def emph(c, e, idx):
    r, g, b = c >> 16, (c >> 8) & 255, c & 255
    if (idx & 0xE) == 0xE:          # video.sv: emphasis only applies in the draw range
        e = 0
    def q(v, s): return v - (v >> s)
    tbl = {0: (r, g, b), 1: (r, q(g, 2), q(b, 2)), 2: (q(r, 2), g, q(b, 2)),
           3: (q(r, 2), q(g, 3), b - (b >> 2) - (b >> 3)), 4: (q(r, 3), q(g, 3), b),
           5: (q(r, 3), q(g, 2), q(b, 3)), 6: (q(r, 2), q(g, 3), q(b, 3)), 7: (q(r, 2), q(g, 2), q(b, 2))}
    return tbl[e]
lines = []
for e in range(8):
    for i in range(64):
        r, g, b = emph(pal[i], e, i)
        r5, g5, b5 = [(v * 31 + 127) // 255 for v in (r, g, b)]
        lines.append(f"\t\t9'd{e*64+i}: q <= 15'h{(b5 << 10) | (g5 << 5) | r5:04X};")
(out / 'nes_palette_rom.sv').write_text(HDR + '''// NES colour -> BGR555, 512 x 15 (one BSRAM as ROM). Registered output.
module nes_palette_rom(input clk, input [8:0] addr, output reg [14:0] q);
	always @(posedge clk) begin
		case (addr)
''' + '\n'.join(lines) + '''
		default: q <= 15'h0000;
		endcase
	end
endmodule
''')
print('wrote nes_palette_rom.sv')

# ---------------------------------------------------------------- APU channel save states
# Upstream saves only the APU top, DMC and frame counter: the square, triangle and noise
# channels (timers, sequencers, length counters, envelopes, sweeps) keep whatever state they
# had when a state is loaded, so audio after a load differs (notes held or cut, other phase).
# Add their registers to the savestate bus (indices 20-23 and 25, unused upstream): every
# channel module gets ss_load/ss_in/ss_out; while SaveStateBus_load is high the registers are
# loaded from the savestate registers.
t = (out / 'apu.sv').read_text()
SS = {  # module -> (state concatenation, width)
    'LenCounterUnit': ('{lc_on, len_counter_int, halt, len_counter_next, lc_on_1, clear_next}', 20),
    'EnvelopeUnit': ('{env_count, env_vol, env_disabled, env_div, env_reload, env_loop}', 15),
    'SquareChan': ('{Duty, SweepEnable, SweepNegate, SweepReset, SweepPeriod, SweepDivider, SweepShift, Period, TimerCtr[10:0], SeqPos}', 39),
    'TriangleChan': ('{Period, applied_period, TimerCtr, SeqPos, LinCtrPeriod, LinCtrPeriod_1, LinCtr, LinCtrl, line_reload, sample_latch}', 65),
    'NoiseChan': ('{ShortMode, Shift, Period, noise_timer, noise_clock}', 32),
}
SUB = {'SquareChan': [('LenSq', 'LenCounterUnit'), ('EnvSq', 'EnvelopeUnit')],
       'TriangleChan': [('LenTri', 'LenCounterUnit')],
       'NoiseChan': [('LenNoi', 'LenCounterUnit'), ('EnvNoi', 'EnvelopeUnit')]}
def total(m):
    return SS[m][1] + sum(SS[c][1] for _, c in SUB.get(m, []))
def patch_mod(t, m):
    a = t.index('module ' + m + ' (')
    b = t.index('endmodule', a)
    body = t[a:b]
    w = total(m)
    # ports
    body = body.replace('\n);', f',\n\tinput  logic       ss_load,\n\tinput  logic [{w-1}:0] ss_in,\n\toutput logic [{w-1}:0] ss_out\n);', 1)
    # hoist block-local declarations of the named always blocks
    def hoist(mm):
        decls = mm.group(2)
        return decls.replace('\t\t', '\t') + '\n\t' + mm.group(1)
    body = re.sub(r'(always_ff @\(posedge clk\) begin : \w+\n)((?:\t\t(?:logic|reg)\b[^\n]*\n)+)', hoist, body)
    # sub-units
    lo = SS[m][1]
    parts = [SS[m][0]]
    for inst, cm in SUB.get(m, []):
        cw = SS[cm][1]
        body = re.sub(r'(' + cm + r' ' + inst + r' \(\n)', r'\1' + f'\t\t.ss_load        (ss_load),\n\t\t.ss_in          (ss_in[{lo+cw-1}:{lo}]),\n\t\t.ss_out         (ss_out[{lo+cw-1}:{lo}]),\n', body, count=1)
        lo += cw
    # load: last statement of the (last) clocked block of this module
    k = body.rindex('\tend\n')
    st, _ = SS[m]
    body = body[:k] + f'\t\tif (ss_load) {st} <= ss_in[{SS[m][1]-1}:0];\n' + body[k:]
    body += f'\tassign ss_out[{SS[m][1]-1}:0] = {st};\n\n'
    return t[:a] + body + t[b:]
for m in SS:
    t = patch_mod(t, m)
# Square TimerCtr is 12 bits wide but never exceeds 11: load the top bit as 0.
t = t.replace('{Duty, SweepEnable, SweepNegate, SweepReset, SweepPeriod, SweepDivider, SweepShift, Period, TimerCtr[10:0], SeqPos} <= ss_in[38:0];',
              '{Duty, SweepEnable, SweepNegate, SweepReset, SweepPeriod, SweepDivider, SweepShift, Period, TimerCtr, SeqPos} <= {ss_in[38:14], 1\'b0, ss_in[13:0]};')
# APU top: 5 more savestate registers, wired into the channel instances
W = 2 * total('SquareChan') + total('TriangleChan') + total('NoiseChan')
assert W <= 320, W
t = t.replace('''	localparam SAVESTATE_MODULES    = 3;
	wire [63:0] SaveStateBus_wired_or[0:SAVESTATE_MODULES-1];
	assign SaveStateBus_Dout = SaveStateBus_wired_or[0] | SaveStateBus_wired_or[1] | SaveStateBus_wired_or[2];''',
f'''	localparam SAVESTATE_MODULES    = 8;
	wire [63:0] SaveStateBus_wired_or[0:SAVESTATE_MODULES-1];
	assign SaveStateBus_Dout = SaveStateBus_wired_or[0] | SaveStateBus_wired_or[1] | SaveStateBus_wired_or[2] |
		SaveStateBus_wired_or[3] | SaveStateBus_wired_or[4] | SaveStateBus_wired_or[5] | SaveStateBus_wired_or[6] | SaveStateBus_wired_or[7];
	// Chromatic: channel state (gen_rtl.py), {{noise, triangle, square2, square1}} in 5 registers
	wire [319:0] SS_CH, SS_CH_BACK;
	eReg_SavestateV #(10'd20, 64'd0) iREG_SAVESTATE_APU_CH0 (clk, SaveStateBus_Din, SaveStateBus_Adr, SaveStateBus_wren, SaveStateBus_rst, SaveStateBus_wired_or[3], SS_CH_BACK[ 63:  0], SS_CH[ 63:  0]);
	eReg_SavestateV #(10'd21, 64'd0) iREG_SAVESTATE_APU_CH1 (clk, SaveStateBus_Din, SaveStateBus_Adr, SaveStateBus_wren, SaveStateBus_rst, SaveStateBus_wired_or[4], SS_CH_BACK[127: 64], SS_CH[127: 64]);
	eReg_SavestateV #(10'd22, 64'd0) iREG_SAVESTATE_APU_CH2 (clk, SaveStateBus_Din, SaveStateBus_Adr, SaveStateBus_wren, SaveStateBus_rst, SaveStateBus_wired_or[5], SS_CH_BACK[191:128], SS_CH[191:128]);
	eReg_SavestateV #(10'd23, 64'd0) iREG_SAVESTATE_APU_CH3 (clk, SaveStateBus_Din, SaveStateBus_Adr, SaveStateBus_wren, SaveStateBus_rst, SaveStateBus_wired_or[6], SS_CH_BACK[255:192], SS_CH[255:192]);
	eReg_SavestateV #(10'd25, 64'd0) iREG_SAVESTATE_APU_CH4 (clk, SaveStateBus_Din, SaveStateBus_Adr, SaveStateBus_wren, SaveStateBus_rst, SaveStateBus_wired_or[7], SS_CH_BACK[319:256], SS_CH[319:256]);
	assign SS_CH_BACK[319:{W}] = '0;''')
lo = 0
for inst, m in [('Squ1', 'SquareChan'), ('Squ2', 'SquareChan'), ('Tri', 'TriangleChan'), ('Noi', 'NoiseChan')]:
    w = total(m)
    t = sub1(t, f'\t{m} {inst} (\n', f'\t{m} {inst} (\n\t\t.ss_load      (SaveStateBus_load),\n\t\t.ss_in        (SS_CH[{lo+w-1}:{lo}]),\n\t\t.ss_out       (SS_CH_BACK[{lo+w-1}:{lo}]),\n')
    lo += w
(out / 'apu.sv').write_text(t)
print('apu.sv: channel save state', W, 'bits')

# ---------------------------------------------------------------- T65.vhd (for the GHDL netlist)
# Upstream holds the CPU in its 2-cycle reset synchronizer after the savestate reset pulse, so
# a loaded state resumes 2 CPU cycles late relative to the PPU/APU (audio and raster timing
# then differ from the run that was saved). Release the synchronizer at once while a state is
# being loaded (SaveStateBus_load); normal resets are unchanged.
v = (work / 'NES_MiSTer' / 'rtl' / 't65' / 'T65.vhd').read_text()
v = sub1(v, """    elsif Clk'event and Clk = '1' and Enable = '1' then
      Res_n_i <= Res_n_d;
      Res_n_d <= '1';
    end if;""", """    elsif Clk'event and Clk = '1' then
      if SaveStateBus_load = '1' then   -- Chromatic (gen_rtl.py): savestate load
        Res_n_i <= '1';
        Res_n_d <= '1';
      elsif Enable = '1' then
        Res_n_i <= Res_n_d;
        Res_n_d <= '1';
      end if;
    end if;""")
v = sub1(v, "process (Res_n, Clk, Enable)", "process (Res_n, Clk, Enable, SaveStateBus_load)")
(out / 'T65.vhd').write_text('-- GENERATED by tools/gen_rtl.py from NES_MiSTer rtl/t65/T65.vhd. Do not edit.\n' + v)
print('wrote T65.vhd (savestate reset synchronizer patch)')

# ---------------------------------------------------------------- Mapper69 IRQ acknowledge
# FME-7: any write to the IRQ control register ($D) acknowledges the IRQ. Upstream only drops
# it when the IRQ is disabled, so a handler that re-enables it (Holy Mapperel's FME-7 test) is
# re-entered forever.
t = (out / 'mappers.sv').read_text()
t = sub1(t, "\t\t\t\t\t13:              {irq_countdown, irq_trigger} <= {prg_din[7], prg_din[0]};",
         "\t\t\t\t\t13:              begin {irq_countdown, irq_trigger} <= {prg_din[7], prg_din[0]}; irq <= 1'b0; end // Chromatic: acknowledge")
(out / 'mappers.sv').write_text(t)
print('mappers.sv: FME-7 IRQ acknowledge on $D writes')
