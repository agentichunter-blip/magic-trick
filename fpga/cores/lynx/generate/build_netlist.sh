#!/bin/bash
# Generate generated/lynx_chromatic.v from lynx-rtl/ (the VHDL is the source of
# truth). Gowin builds this GHDL netlist, the same one tests/sim simulates:
# Gowin's own VHDL front end produced a core whose save-state register bus
# read back all ones on hardware.
set -euo pipefail
cd "$(dirname "$0")/.."
G=${GHDL:-$(cd ../../../.. && pwd)/toolchains/oss-cad-suite/bin/ghdl}
W=$(mktemp -d)
F="--std=08 -frelaxed -fsynopsys --workdir=$W"
$G -i $F lynx-rtl/*.vhd
$G -m $F lynx_chromatic
{ echo "// Generated by generate/build_netlist.sh from lynx-rtl/ with GHDL --synth. Do not edit."
  $G --synth $F --out=verilog lynx_chromatic; } > generated/lynx_chromatic.v
rm -rf "$W"
echo "generated/lynx_chromatic.v: $(wc -l < generated/lynx_chromatic.v) lines"
