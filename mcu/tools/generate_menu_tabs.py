"""Extract the stock selected-tab glyphs for the shared six-tab strip."""
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
lines=['/* Generated by tools/generate_menu_tabs.py from the stock menu artwork. */','#include "lvgl.h"']
for i,name in enumerate(['status','display','controls','palette','system']):
 im=Image.open(root/'components/images'/f'menu_{name}.png').convert('RGB')
 pixels=[]
 for y in range(4,13):
  bits=0
  for x in range(9):
   if im.getpixel((8+i*18+5+x,y))==(255,255,255):bits|=1<<(15-x)
  pixels.extend([bits>>8,bits&255])
 lines.append(f'static const uint8_t TabGlyph{i}[]={{'+','.join(f'0x{n:02x}' for n in pixels)+'};')
lines.append('static const lv_img_dsc_t NativeTabGlyphs[]={')
for i in range(5):lines.append(f' {{.header={{.cf=LV_IMG_CF_ALPHA_1BIT,.w=9,.h=9}},.data_size=sizeof(TabGlyph{i}),.data=TabGlyph{i}}},')
lines.append('};')
(root/'components/menu_mgr/tab_glyphs.h').write_text('\n'.join(lines)+'\n')
