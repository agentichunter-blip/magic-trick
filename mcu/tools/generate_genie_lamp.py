#!/usr/bin/env python3
"""Generate native LVGL one-bit lamp icons from hand-drawn pixel grids.
Original lamp/smoke silhouettes, inspired by cheat-device-era pixel graphics;
not a reproduction of a supplied logo. No external image assets required.
"""
from pathlib import Path

outline = [
'      ##',
'     #',
'      ##',
'        #',
'       #',
'      ###',
'     #####',
' ########### ##',
'  #        ##  #',
'   ##      #   #',
'     ###### ###',
'       ##',
'      ####',
'     ######',
]
filled = outline.copy()
filled[8] = '  ###########  #'
filled[9] = '   #########   #'
large = [
'         ###',
'        #   #',
'         #',
'          ###',
'             #',
'            #',
'          #####',
'        #########',
'  ################  ###',
'   ############### #   #',
'    ###############    #',
'      ############ #   #',
'        #########   ###',
'           ###',
'          #####',
'        #########',
]

def emit(name,width,rows):
    assert width % 8 == 0 and all(len(row)<=width for row in rows)
    data=[]
    for row in rows:
        row=row.ljust(width)
        for x in range(0,width,8):
            data.append(sum((1<<(7-i)) for i,c in enumerate(row[x:x+8]) if c=='#'))
    values=', '.join(f'0x{b:02x}' for b in data)
    return f'''static const uint8_t {name}Pixels[] = {{ {values} }};
static const lv_img_dsc_t {name} = {{
    .header = {{ .cf=LV_IMG_CF_ALPHA_1BIT, .w={width}, .h={len(rows)} }},
    .data_size=sizeof({name}Pixels), .data={name}Pixels
}};
'''

if __name__=='__main__':
    dest=Path(__file__).resolve().parents[1]/'components/osd/system/genie_lamp.h'
    dest.write_text('/* Generated by tools/generate_genie_lamp.py. Original pixel art. */\n#pragma once\n'+emit('GenieLampOutline',16,outline)+emit('GenieLampFilled',16,filled)+emit('GenieLampLogo',24,large))
