#include <assert.h>
#include <stdio.h>
#include <string.h>
#include "lynx_hle.h"
#include "lynx_hle_boot.h"
/* cc65's signed one-block loader (libsrc/lynx/bootldr.s) and its plaintext. */
static const uint8_t Encrypted[52] = {
 0xff,0xb6,0xbb,0x82,0xd5,0x9f,0x48,0xcf,0x23,0x37,0x8e,0x07,0x38,0xf5,0xb6,0x30,
 0xd6,0x2f,0x12,0x29,0x9f,0x43,0x5b,0x2e,0xf5,0x66,0x5c,0xdb,0x93,0x1a,0x78,0x55,
 0x5e,0xc9,0x0d,0x72,0x1b,0xe9,0xd8,0x4d,0x2f,0xe4,0x95,0xc0,0x4f,0x7f,0x1b,0x66,
 0x8b,0xa7,0xfc,0x21};
static const uint8_t Plain[50] = {
 0x9c,0xf9,0xff,0xa0,0x1f,0xa9,0x00,0x99,0xa0,0xfd,0x88,0x10,0xfa,0xa9,0x04,0x8d,
 0x8c,0xfd,0xa9,0x1a,0x8d,0x8a,0xfd,0xa9,0x0b,0x85,0x1a,0x8d,0x8b,0xfd,0xa2,0x00,
 0xa0,0x97,0xad,0xb2,0xfc,0x9d,0x68,0xfb,0xe8,0x88,0xd0,0xf6,0x4c,0x68,0xfb,0x00,
 0x00,0x00};
int main(void)
{
    uint8_t Loader[256]; size_t Length = 0;
    assert(LynxHle_Decrypt(Encrypted, sizeof(Encrypted), Loader, &Length) == ESP_OK);
    assert(Length == 50 && !memcmp(Loader, Plain, 50));
    uint8_t Boot[512];
    assert(LynxHle_BuildBoot(Encrypted, sizeof(Encrypted), Boot) == ESP_OK);
    assert(!memcmp(Boot + kLynxHleLoader, Plain, 50) && Boot[kLynxHleSkipLo] == 52 && Boot[kLynxHleSkipHi] == 0);
    assert(Boot[0x1fc] == 0x80 && Boot[0x1fd] == 0xff && Boot[0x180] == 0x78); /* reset at $FF80 */
    /* 5 blocks: 256 bytes to skip -> SKIPLO 0, SKIPHI 0 (the loop reads 256). */
    uint8_t Five[256]; memset(Five, 0, sizeof(Five)); Five[0] = 0xfb;
    assert(LynxHle_BuildBoot(Five, sizeof(Five), Boot) == ESP_OK);
    assert(Boot[kLynxHleSkipLo] == 0 && Boot[kLynxHleSkipHi] == 0);
    uint8_t Six[400] = {0xfa};
    assert(LynxHle_Decrypt(Six, sizeof(Six), Loader, &Length) != ESP_OK);
    assert(LynxHle_Decrypt(Encrypted, 20, Loader, &Length) != ESP_OK);
    puts("PASS: Lynx loader decryption (cc65 vector), boot stub patching, limits");
    return 0;
}
